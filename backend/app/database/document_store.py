"""Persistent document registry and ChromaDB vector storage.

The JSON registry holds document-level metadata; ChromaDB holds passage vectors
on disk. Both live under server-controlled directories. Unsafe IDs are rejected
before any path is constructed, and IDs are generated by the service — never
accepted from an upload.
"""

from __future__ import annotations

import json
import logging
import re
import threading
from pathlib import Path

from pydantic import ValidationError

from app.models.documents import DocumentDetail
from app.services.chunker import DocumentChunk
from app.services.embeddings import EmbeddingProvider

logger = logging.getLogger(__name__)


class DocumentStoreError(RuntimeError):
    """Raised when persistent document storage cannot be used."""


class DocumentRegistry:
    """Atomic, thread-safe JSON registry of document-level records."""

    def __init__(self, index_path: Path) -> None:
        self._index_path = Path(index_path)
        self._lock = threading.RLock()

    def _load(self) -> list[DocumentDetail]:
        if not self._index_path.exists():
            return []
        try:
            payload = json.loads(self._index_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            logger.exception("Document index could not be read")
            raise DocumentStoreError("The document index could not be read.") from exc
        if not isinstance(payload, list):
            raise DocumentStoreError("The document index has an invalid format.")
        try:
            return [DocumentDetail.model_validate(item) for item in payload]
        except ValidationError as exc:
            logger.error("Document index failed validation: %s", exc)
            raise DocumentStoreError("The document index is invalid.") from exc

    def _write(self, records: list[DocumentDetail]) -> None:
        payload = [record.model_dump(mode="json") for record in records]
        temporary = self._index_path.with_suffix(".json.tmp")
        try:
            self._index_path.parent.mkdir(parents=True, exist_ok=True)
            temporary.write_text(
                json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8"
            )
            temporary.replace(self._index_path)
        except OSError as exc:
            logger.exception("Document index could not be written")
            raise DocumentStoreError("The document index could not be saved.") from exc

    def list(self) -> list[DocumentDetail]:
        with self._lock:
            records = self._load()
        return sorted(records, key=lambda record: record.uploaded_at, reverse=True)

    def get(self, document_id: str) -> DocumentDetail | None:
        with self._lock:
            return next(
                (
                    record
                    for record in self._load()
                    if record.document_id == document_id
                ),
                None,
            )

    def find_by_checksum(self, checksum: str) -> DocumentDetail | None:
        with self._lock:
            return next(
                (record for record in self._load() if record.checksum == checksum),
                None,
            )

    def add(self, record: DocumentDetail) -> None:
        with self._lock:
            records = self._load()
            records.append(record)
            self._write(records)

    def delete(self, document_id: str) -> DocumentDetail | None:
        with self._lock:
            records = self._load()
            target = next(
                (record for record in records if record.document_id == document_id),
                None,
            )
            if target is None:
                return None
            self._write([record for record in records if record is not target])
            return target


class VectorStore:
    """ChromaDB collection of page-aware passages with cosine distance."""

    def __init__(self, persist_dir: Path, collection_name: str) -> None:
        self._persist_dir = Path(persist_dir)
        self.collection_name = collection_name
        try:
            import chromadb
        except ImportError as exc:
            raise DocumentStoreError(
                "ChromaDB is not installed on the server."
            ) from exc
        try:
            client = chromadb.PersistentClient(path=str(self._persist_dir))
            self._collection = client.get_or_create_collection(
                name=collection_name,
                metadata={"hnsw:space": "cosine"},
            )
        except Exception as exc:
            logger.exception("ChromaDB could not be initialised")
            raise DocumentStoreError(
                "The persistent vector store could not be opened."
            ) from exc

    def add_document_chunks(
        self,
        *,
        document_id: str,
        original_filename: str,
        checksum: str,
        chunks: list[DocumentChunk],
        embedder: EmbeddingProvider,
    ) -> int:
        """Insert or replace every chunk of one document (idempotent)."""
        if not chunks:
            return 0
        vectors = embedder.embed_passages([chunk.text for chunk in chunks])
        if len(vectors) != len(chunks):
            raise DocumentStoreError(
                "The embedder returned the wrong number of vectors."
            )
        ids = [f"{document_id}:{chunk.chunk_index}" for chunk in chunks]
        metadatas: list[dict[str, str | int]] = [
            {
                "document_id": document_id,
                "document_name": original_filename,
                "original_filename": original_filename,
                "checksum": checksum,
                "page_number": int(chunk.page_number),
                "chunk_index": int(chunk.chunk_index),
                "source": "pdf",
            }
            for chunk in chunks
        ]
        try:
            self._collection.upsert(
                ids=ids,
                embeddings=vectors,
                documents=[chunk.text for chunk in chunks],
                metadatas=metadatas,
            )
        except Exception as exc:
            logger.exception("ChromaDB could not store %s chunks", len(chunks))
            raise DocumentStoreError("Passages could not be indexed.") from exc
        return len(ids)

    def search(
        self,
        query_embedding: list[float],
        top_k: int,
        document_id: str | None = None,
    ) -> list[dict[str, object]]:
        """Return raw nearest passages, optionally restricted to one document."""
        total = self._collection.count()
        if total == 0:
            return []
        where = {"document_id": document_id} if document_id else None
        kwargs: dict[str, object] = {
            "query_embeddings": [query_embedding],
            "n_results": max(1, min(top_k, total)),
            "include": ["documents", "metadatas", "distances"],
        }
        if where:
            kwargs["where"] = where
        try:
            result = self._collection.query(**kwargs)
        except Exception as exc:
            logger.exception("ChromaDB semantic search failed")
            raise DocumentStoreError("Semantic search could not be completed.") from exc

        ids = (result.get("ids") or [[]])[0]
        documents = (result.get("documents") or [[]])[0]
        metadatas = (result.get("metadatas") or [[]])[0]
        distances = (result.get("distances") or [[]])[0]
        return [
            {
                "id": chunk_id,
                "text": text,
                "metadata": metadata or {},
                "distance": float(distance),
            }
            for chunk_id, text, metadata, distance in zip(
                ids, documents, metadatas, distances
            )
            if text
        ]

    def count_for_document(self, document_id: str) -> int:
        try:
            result = self._collection.get(
                where={"document_id": document_id}, include=[]
            )
        except Exception as exc:
            logger.exception("ChromaDB count for document failed")
            raise DocumentStoreError("Indexed passages could not be counted.") from exc
        return len(result.get("ids") or [])

    def delete_document(self, document_id: str) -> int:
        """Delete only this document's vectors; unrelated documents are untouched."""
        count = self.count_for_document(document_id)
        if count == 0:
            return 0
        try:
            self._collection.delete(where={"document_id": document_id})
        except Exception as exc:
            logger.exception("ChromaDB could not delete document %s", document_id)
            raise DocumentStoreError(
                "The document's passages could not be deleted."
            ) from exc
        return count

    def status(self) -> dict[str, object]:
        try:
            count = self._collection.count()
        except Exception as exc:
            logger.exception("ChromaDB status check failed")
            return {"available": False, "chunk_count": 0, "detail": str(exc)}
        return {
            "available": True,
            "chunk_count": count,
            "detail": f"Persistent collection '{self.collection_name}' holds {count} indexed passages.",
        }


class DocumentStore:
    """Facade combining the registry, vector store and controlled file paths."""

    def __init__(
        self, storage_dir: Path, chroma_dir: Path, collection_name: str
    ) -> None:
        self.storage_dir = Path(storage_dir)
        try:
            self.storage_dir.mkdir(parents=True, exist_ok=True)
        except OSError as exc:
            logger.exception("Document storage directory could not be created")
            raise DocumentStoreError(
                "The document storage directory is unavailable."
            ) from exc
        self.registry = DocumentRegistry(self.storage_dir / "index.json")
        self.vectors = VectorStore(chroma_dir, collection_name)

    def pdf_path(self, document_id: str) -> Path:
        """Build a storage path from a server-generated id, with containment check."""
        if not re.fullmatch(r"[A-Za-z0-9_-]+", document_id):
            raise DocumentStoreError("Unsafe document identifier.")
        base = self.storage_dir.resolve()
        path = (base / f"{document_id}.pdf").resolve()
        if path.parent != base:
            raise DocumentStoreError("Unsafe document path.")
        return path
